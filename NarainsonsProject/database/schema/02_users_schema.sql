USE narainson_db;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    customer_code VARCHAR(50) UNIQUE,
    name VARCHAR(150) NOT NULL,
    first_name VARCHAR(80),
    last_name VARCHAR(80),
    mobile_number VARCHAR(20) NOT NULL UNIQUE,
    alternate_mobile_number VARCHAR(20),
    email VARCHAR(150) UNIQUE,
    gender ENUM('Male','Female','Other'),
    date_of_birth DATE,
    age SMALLINT,
    marital_status ENUM('Single','Married','Divorced','Widowed'),
    nationality VARCHAR(80) DEFAULT 'Indian',
    profile_image VARCHAR(500),
    aadhaar_encrypted TEXT,
    aadhaar_last4 CHAR(4),
    pan_encrypted TEXT,
    pan_last4 VARCHAR(4),
    aadhaar_document VARCHAR(500),
    pan_document VARCHAR(500),
    kyc_status ENUM('pending','submitted','verified','rejected') DEFAULT 'pending',
    kyc_verified_at DATETIME,
    kyc_rejection_reason TEXT,
    current_address TEXT,
    current_city VARCHAR(100),
    current_state VARCHAR(100),
    current_pincode VARCHAR(10),
    current_country VARCHAR(80) DEFAULT 'India',
    permanent_address TEXT,
    permanent_city VARCHAR(100),
    permanent_state VARCHAR(100),
    permanent_pincode VARCHAR(10),
    permanent_country VARCHAR(80) DEFAULT 'India',
    same_as_current_address BOOLEAN DEFAULT FALSE,
    employment_type ENUM('Salaried','Self Employed','Business','Professional','Unemployed','Other'),
    company_name VARCHAR(200),
    designation VARCHAR(150),
    work_experience_months INT,
    monthly_income DECIMAL(15,2),
    annual_income DECIMAL(15,2),
    income_source VARCHAR(150),
    bank_name VARCHAR(150),
    bank_account_encrypted TEXT,
    bank_account_last4 CHAR(4),
    ifsc_code VARCHAR(15),
    bank_verification_status ENUM('pending','verified','failed') DEFAULT 'pending',
    bank_verified_at DATETIME,
    password_hash VARCHAR(255),
    otp_hash VARCHAR(255),
    otp_expires_at DATETIME,
    otp_verified_at DATETIME,
    email_verified_at DATETIME,
    mobile_verified_at DATETIME,
    login_attempts INT DEFAULT 0,
    locked_until DATETIME,
    last_login DATETIME,
    last_logout_at DATETIME,
    account_status ENUM('active','inactive','blocked','suspended') DEFAULT 'active',
    fcm_token TEXT,
    fcm_token_updated_at DATETIME,
    notification_enable BOOLEAN DEFAULT TRUE,
    notification_disable_at DATETIME,
    device_id VARCHAR(255),
    device_type VARCHAR(50),
    device_name VARCHAR(150),
    device_model VARCHAR(150),
    os_version VARCHAR(100),
    app_version VARCHAR(50),
    time_zone VARCHAR(100),
    is_login BOOLEAN DEFAULT FALSE,
    is_app_installed BOOLEAN DEFAULT TRUE,
    application_install_time DATETIME,
    application_uninstall_time DATETIME,
    latitude DECIMAL(10,7),
    longitude DECIMAL(10,7),
    privacy_consent BOOLEAN DEFAULT FALSE,
    privacy_consent_at DATETIME,
    terms_accepted BOOLEAN DEFAULT FALSE,
    terms_accepted_at DATETIME,
    kyc_consent BOOLEAN DEFAULT FALSE,
    kyc_consent_at DATETIME,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME,
    INDEX idx_customer_mobile (mobile_number),
    INDEX idx_customer_email (email),
    INDEX idx_customer_kyc (kyc_status),
    INDEX idx_customer_status (account_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
